import * as THREE from "three/webgpu";
import type { Landscape } from "./world/landscape";
import type { TerrainResult } from "./world/gen";
import { terrainMaterial } from "./terrainMaterial";
import { BatchPool } from "./batchPool";
import type { Vegetation } from "./vegetation";
import type { WorldWorkers } from "./worldWorkers";

const TILE = 128;
const RADIUS = 2200;
/** Vertex spacing per level of detail, and the distance (tile centre to camera) each is used up to. */
const LODS = [
  { segments: 64, within: 300 },
  { segments: 32, within: 700 },
  { segments: 16, within: 1400 },
  { segments: 8, within: Infinity },
];
/** Trees are planted this far out (billboards beyond the near tiles). */
const TREES_WITHIN = 2050;
/**
 * Beyond this distance, whole blocks of BLOCK x BLOCK tiles are built as one mesh (same
 * vertex spacing), cutting draw calls: each costs CPU time and garbage in the renderer.
 */
const COARSE_FROM = 700;
/** Squares being generated at once (the workers take them in order, nearest first). */
const IN_FLIGHT = 6;
/** Finished squares turned into meshes per frame (each a GPU upload). */
const APPLY_PER_FRAME = 3;

/** Terrain blocks (and vegetation pools) span BLOCK x BLOCK tiles. */
const BLOCK = 4;

interface Tile {
  key: string;
  /** What it was built as; rebuilt when the wanted one differs. */
  sig: string;
  /** Its piece in the batch. */
  piece: number;
  /** Vegetation it scattered, per 128 m tile key, and whether as far (trees only). */
  trees: [string, Float32Array, boolean][];
}

/** A square of terrain to build: one tile, or a whole block far away. */
interface Wanted {
  key: string;
  sig: string;
  x0: number;
  z0: number;
  size: number;
  segments: number;
  /** Tiles (tx, tz) to scatter vegetation on, and whether as far (trees only, sparser). */
  treeTiles: [number, number, boolean][];
  dist: number;
}

/**
 * Streams terrain tiles (with skirts to hide LOD cracks) and trees around a focus point.
 * Tiles are generated by the world workers; this only turns their arrays into meshes.
 */
export class TerrainView {
  readonly group = new THREE.Group();
  private readonly tiles = new Map<string, Tile>();
  /** All terrain is one batched object: one draw per visible tile, without per-mesh overhead. */
  private readonly batch: BatchPool;

  constructor(
    private readonly land: Landscape,
    private readonly vegetation: Vegetation,
    private readonly workers: WorldWorkers,
  ) {
    // Sized for the peak while driving: ~410k vertices in view, plus tiles kept until their
    // replacements are in and free slots of other levels of detail.
    this.batch = new BatchPool(terrainMaterial(land.road.edge), {
      vertices: 900_000,
      indices: 4_800_000,
      instances: 1024,
    });
    this.batch.mesh.name = "terrain";
    // Receives the car's shadow; its own come from the SunField.
    this.batch.mesh.receiveShadow = true;
    this.group.add(this.batch.mesh);
  }

  /** Squares wanted around the last focus tile, nearest first, and how many are done. */
  private wanted: Wanted[] = [];
  private done = 0;
  private scanKey = "";
  private keep = new Set<string>();
  /** Squares being generated (key -> what they're built as), and those finished. */
  private readonly building = new Map<string, string>();
  private readonly finished: { w: Wanted; r: TerrainResult }[] = [];
  private readonly jobs = new Set<Promise<void>>();
  /** Terrain no longer wanted, kept until its replacement is built so no gaps show. */
  private retiring = new Map<string, Tile>();

  /**
   * Requests missing terrain nearest-first from the workers and turns finished squares
   * into meshes (a few per frame); drops terrain no longer wanted once its replacements
   * are in. The wanted set is only recomputed when the focus enters another tile or the
   * road grows.
   */
  update(
    focus: THREE.Vector3,
    inFlight = IN_FLIGHT,
    apply = APPLY_PER_FRAME,
  ): void {
    const fx = Math.floor(focus.x / TILE);
    const fz = Math.floor(focus.z / TILE);
    const gate = Math.floor(this.land.road.finalProgress / TILE);
    const scanKey = `${fx},${fz},${gate}`;
    if (scanKey !== this.scanKey) {
      this.scanKey = scanKey;
      this.rescan(fx, fz);
    }
    for (let n = 0; n < apply && this.finished.length; n++)
      this.apply(this.finished.shift()!);
    while (this.building.size < inFlight && this.done < this.wanted.length) {
      const w = this.wanted[this.done++]!;
      const existing = this.tiles.get(w.key);
      if (existing && existing.sig === w.sig) continue;
      if (this.building.get(w.key) === w.sig) continue;
      this.request(w);
    }
    if (
      this.done === this.wanted.length &&
      this.building.size === 0 &&
      this.finished.length === 0 &&
      this.retiring.size
    ) {
      for (const [key, tile] of this.retiring) this.drop(key, tile);
      this.retiring.clear();
    }
  }

  /** Builds everything around `focus` (start-up), as fast as the workers go. */
  async prime(focus: THREE.Vector3): Promise<void> {
    this.update(focus, Infinity, 0);
    while (this.jobs.size) await Promise.all(this.jobs);
    this.update(focus, Infinity, Infinity);
  }

  private request(w: Wanted): void {
    this.building.set(w.key, w.sig);
    const job = this.workers
      .run({
        kind: "terrain",
        x0: w.x0,
        z0: w.z0,
        size: w.size,
        segments: w.segments,
        tile: TILE,
        treeTiles: w.treeTiles,
      })
      .then((r) => {
        this.jobs.delete(job);
        if (this.building.get(w.key) === w.sig) this.building.delete(w.key);
        this.finished.push({ w, r });
      });
    this.jobs.add(job);
  }

  private rescan(fx: number, fz: number): void {
    // Distances from the focus tile's centre, so the set only depends on the tile.
    const cx = (fx + 0.5) * TILE;
    const cz = (fz + 0.5) * TILE;
    const final = this.land.road.finalProgress;
    // Only build where the road can no longer change: its future lies further along -Z.
    const settled = (tz: number) => -tz * TILE + 64 <= final;
    const span = BLOCK * TILE;
    const reach = Math.ceil(RADIUS / span) + 1;
    const bx0 = Math.floor(fx / BLOCK);
    const bz0 = Math.floor(fz / BLOCK);
    const wanted: Wanted[] = [];
    for (let bx = bx0 - reach; bx <= bx0 + reach; bx++)
      for (let bz = bz0 - reach; bz <= bz0 + reach; bz++) {
        const nearest = Math.hypot(
          Math.max(bx * span - cx, 0, cx - (bx + 1) * span),
          Math.max(bz * span - cz, 0, cz - (bz + 1) * span),
        );
        if (nearest > RADIUS) continue;
        if (nearest > COARSE_FROM && settled(bz * BLOCK)) {
          const per = nearest <= LODS[2]!.within ? 16 : 8;
          const treeTiles: [number, number, boolean][] = [];
          for (let i = 0; i < BLOCK; i++)
            for (let j = 0; j < BLOCK; j++) {
              const tx = bx * BLOCK + i;
              const tz = bz * BLOCK + j;
              const d = Math.hypot(
                (tx + 0.5) * TILE - cx,
                (tz + 0.5) * TILE - cz,
              );
              if (d <= TREES_WITHIN) treeTiles.push([tx, tz, true]);
            }
          wanted.push({
            key: `b${bx},${bz}`,
            sig: `${per}`,
            x0: bx * span,
            z0: bz * span,
            size: span,
            segments: per * BLOCK,
            treeTiles,
            dist: nearest,
          });
          continue;
        }
        for (let i = 0; i < BLOCK; i++)
          for (let j = 0; j < BLOCK; j++) {
            const tx = bx * BLOCK + i;
            const tz = bz * BLOCK + j;
            const dist = Math.hypot(
              (tx + 0.5) * TILE - cx,
              (tz + 0.5) * TILE - cz,
            );
            if (dist > RADIUS || !settled(tz)) continue;
            const lod = LODS.findIndex((l) => dist <= l.within);
            wanted.push({
              key: `${tx},${tz}`,
              sig: `${lod}`,
              x0: tx * TILE,
              z0: tz * TILE,
              size: TILE,
              segments: LODS[lod]!.segments,
              treeTiles: dist <= TREES_WITHIN ? [[tx, tz, false]] : [],
              dist,
            });
          }
      }
    const keep = new Set(wanted.map((w) => w.key));
    this.keep = keep;
    for (const [key, tile] of this.tiles)
      if (!keep.has(key)) {
        this.tiles.delete(key);
        this.retiring.set(key, tile);
      }
    // Wanted again before it was dropped: take it back.
    for (const key of keep) {
      const tile = this.retiring.get(key);
      if (tile && !this.tiles.has(key)) {
        this.retiring.delete(key);
        this.tiles.set(key, tile);
      }
    }
    wanted.sort((a, b) => a.dist - b.dist);
    this.wanted = wanted;
    this.done = 0;
  }

  private drop(key: string, tile: Tile, kept?: Set<Float32Array>): void {
    this.batch.remove(tile.piece);
    // Only its own trees: a replacement may have planted the same tile already, or
    // taken these over (`kept`).
    for (const [t, trees] of tile.trees)
      if (!kept?.has(trees)) this.vegetation.remove(t, trees);
    if (this.tiles.get(key) === tile) this.tiles.delete(key);
  }

  /** A generated square in place: its mesh, and its trees handed to the vegetation. */
  private apply({ w, r }: { w: Wanted; r: TerrainResult }): void {
    const { key } = w;
    // No longer wanted after all (the focus moved on while it was built).
    if (!this.keep.has(key)) return;
    const geo = new THREE.BufferGeometry();
    geo.setAttribute("position", new THREE.BufferAttribute(r.position, 3));
    geo.setAttribute("normal", new THREE.BufferAttribute(r.normal, 3));
    geo.setAttribute("variation", new THREE.BufferAttribute(r.variation, 1));
    geo.setAttribute("road", new THREE.BufferAttribute(r.road, 1));
    geo.setAttribute("forest", new THREE.BufferAttribute(r.forest, 1));
    geo.setIndex(new THREE.BufferAttribute(r.index, 1));
    const [cx, cy, cz, radius] = r.sphere;
    geo.boundingSphere = new THREE.Sphere(
      new THREE.Vector3(cx, cy, cz),
      radius,
    );
    const piece = this.batch.add(geo);
    // A tile's trees only depend on whether it's near or far: across other level-of-detail
    // changes the old tile's are kept as they are (re-registering them would rebuild the
    // billboard blocks for nothing).
    const old = this.tiles.get(key);
    const far = new Map(w.treeTiles.map(([tx, tz, f]) => [`${tx},${tz}`, f]));
    const kept = new Set<Float32Array>();
    const trees: Tile["trees"] = [];
    for (const [treeKey, items] of r.trees) {
      const f = far.get(treeKey)!;
      const same = old?.trees.find(([k, , g]) => k === treeKey && g === f);
      if (same) {
        trees.push(same);
        kept.add(same[1]);
        continue;
      }
      trees.push([treeKey, items, f]);
      const [tx, tz] = treeKey.split(",").map(Number) as [number, number];
      this.vegetation.add(
        treeKey,
        (tx + 0.5) * TILE,
        (tz + 0.5) * TILE,
        blockKey(treeKey),
        items,
      );
    }
    if (old) this.drop(key, old, kept);
    const tile: Tile = { key, sig: w.sig, piece, trees };
    this.tiles.set(key, tile);
  }
}

/** Key of the tree block holding tile "tx,tz". */
function blockKey(tileKey: string): string {
  const [tx, tz] = tileKey.split(",").map(Number) as [number, number];
  return `${Math.floor(tx / BLOCK)},${Math.floor(tz / BLOCK)}`;
}
